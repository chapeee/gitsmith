import { readFile } from "node:fs/promises";
import pc from "picocolors";
import { CONFIG_FILE_NAME } from "../config/default.js";
import { findConfigPath, loadValidatedConfig } from "../config/loader.js";
import { checkCommitMessage, exampleHeader } from "../validate/message.js";

async function readStdin() {
  const chunks = [];
  for await (const chunk of process.stdin) {
    chunks.push(chunk);
  }
  return Buffer.concat(chunks).toString("utf8");
}

/**
 * Validates a commit message without committing.
 * Source: the argument, --file (used by the commit-msg hook), or --stdin.
 * Exits with code 1 when the message breaks the rules.
 * @param {string | undefined} messageArg
 * @param {{file?: string, stdin?: boolean, json?: boolean}} options
 */
export async function runCheckCommand(messageArg, options = {}) {
  let raw;
  if (options.file) {
    raw = await readFile(options.file, "utf8");
  } else if (options.stdin) {
    raw = await readStdin();
  } else if (messageArg !== undefined) {
    raw = messageArg;
  } else {
    throw new Error('Pass a message, --file <path> or --stdin. Example: gitsmith check "feat(api): add retry"');
  }

  // From the hook (--file), a repo without a config must not block every commit.
  if (options.file && !(await findConfigPath())) {
    console.error(pc.yellow(`gitsmith: no ${CONFIG_FILE_NAME} found; skipping commit message check.`));
    return;
  }

  const { config } = await loadValidatedConfig();
  const result = checkCommitMessage(raw, config);

  if (options.json) {
    process.stdout.write(`${JSON.stringify({ ...result, example: exampleHeader(config) }, null, 2)}\n`);
  } else if (result.ok) {
    for (const warning of result.warnings) {
      console.error(pc.yellow(`gitsmith warning: ${warning}`));
    }
    if (!options.file) {
      console.log(pc.green(result.skipped ? "Skipped (generated by git)." : "Valid commit message."));
    }
  } else {
    console.error(pc.red(`gitsmith: commit message rejected: "${result.header}"`));
    for (const error of result.errors) {
      console.error(pc.red(`  - ${error}`));
    }
    console.error(pc.cyan(`  Expected format: ${config.format}`));
    console.error(pc.cyan(`  Example: ${exampleHeader(config)}`));
    console.error(pc.cyan('  Run "gitsmith rules" to see every allowed value.'));
  }

  if (!result.ok) {
    process.exitCode = 1;
  }
}
